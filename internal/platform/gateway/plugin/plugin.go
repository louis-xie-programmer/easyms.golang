// Package plugin 定义了 API 网关插件化架构的核心接口和数据结构。
package plugin

// Plugin 是所有网关插件都必须实现的接口。
// 它定义了一个插件的基本行为：名称、执行顺序和核心逻辑。
type Plugin interface {
	// Name 返回插件的唯一名称。
	// 这个名称主要用于日志记录和调试。
	Name() string

	// Order 返回一个整数，用于决定插件的执行顺序。
	// 网关会根据这个数字对所有已注册的插件进行升序排序，数字越小的插件越先执行。
	// 建议在实现插件时，顺序值之间保留一定的间隔 (例如 10)，以便未来在它们之间插入新的插件。
	//
	// 推荐的插件顺序参考:
	// 0-9:   直接响应类插件 (如 Mock, 缓存)，它们可能会直接返回响应而不继续执行后续插件。
	// 10-19: 认证/授权类插件 (Auth)。
	// 20-29: 速率限制类插件 (RateLimit)。
	// 30-39: 路由类插件 (Routing)，负责解析请求并确定目标上游服务。
	// 40-49: 熔断类插件 (CircuitBreaker)。
	// 50-89: 请求/响应转换类插件 (Transformation)，例如修改 Header 或 Body。
	// 90-100: 代理/转发类插件 (Proxy)，负责将请求实际发送到上游服务。
	Order() int

	// Execute 是插件的核心逻辑实现。
	// 它接收一个 Context 对象，其中包含了请求和响应的所有信息。
	//
	// 在方法内部，插件可以执行以下操作：
	// - 读取或修改请求 (ctx.Request)。
	// - 写入响应 (ctx.ResponseWriter)，这可能会中断插件链。
	// - 在上下文中存储数据，以供后续插件使用 (ctx.Set)。
	// - 调用 ctx.Next() 将控制权传递给插件链中的下一个插件。
	//
	// **重要**: 如果一个插件不调用 ctx.Next()，那么插件链的执行将在此中断，
	// 后续的所有插件都不会被执行。这通常用于直接返回响应的插件 (如认证失败、限流、Mock)。
	Execute(ctx *Context)
}
